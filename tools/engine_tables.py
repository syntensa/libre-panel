"""Write engine/src/tables.rs: Pillow's tables for RGB to YCbCr and yuv.py's for the range.

    python tools/engine_tables.py PATH/TO/Pillow/src/libImaging/ConvertYCbCr.c

The engine makes the panel's YUV byte for byte as devices/yuv.py does, which converts with
Pillow; Pillow does it with integer tables (ConvertYCbCr.c, read here as data). They are
checked on all 2^24 colours against the Pillow installed here before they are written, and so
is Pillow's 2x2 average (reduce(2)). tests/test_native_engine.py checks the written file
against Pillow again.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
NAMES = ("Y_R", "Y_G", "Y_B", "Cb_R", "Cb_G", "Cb_B", "Cr_G", "Cr_B")


def tables_of(source: str) -> dict[str, np.ndarray]:
    found = {}
    for name in NAMES:
        body = re.search(rf"static INT16 {name}\[\] = \{{(.*?)\}};", source, re.S)
        values = [int(x) for x in re.findall(r"-?\d+", body.group(1))]
        assert len(values) == 256, name
        found[name] = np.array(values, np.int64)
    found["Cr_R"] = found["Cb_B"]  # (#define Cr_R Cb_B)
    return found


def converted(t: dict[str, np.ndarray], rgb: np.ndarray) -> np.ndarray:
    """YCbCr of the pixels ``rgb`` (n x 3) as Pillow makes it, by the tables ``t``."""
    r, g, b = (rgb[:, i].astype(np.int64) for i in range(3))
    y = (t["Y_R"][r] + t["Y_G"][g] + t["Y_B"][b]) >> 6
    cb = ((t["Cb_R"][r] + t["Cb_G"][g] + t["Cb_B"][b]) >> 6) + 128
    cr = ((t["Cr_R"][r] + t["Cr_G"][g] + t["Cr_B"][b]) >> 6) + 128
    return np.stack([y, cb, cr], axis=-1) & 255


def main() -> int:
    from libre_panel.devices.yuv import LIMITED_C, LIMITED_Y

    t = tables_of(Path(sys.argv[1]).read_text())
    v = np.arange(1 << 24, dtype=np.uint32)
    rgb = np.stack([(v >> 16) & 255, (v >> 8) & 255, v & 255], axis=-1).astype(np.uint8)
    pillow = np.asarray(Image.fromarray(rgb.reshape(4096, 4096, 3), "RGB").convert("YCbCr"))
    assert np.array_equal(converted(t, rgb), pillow.reshape(-1, 3)), "not Pillow's conversion"
    c = np.random.default_rng(1).integers(0, 256, (64, 64), np.uint8)
    q = c.astype(np.int64).reshape(32, 2, 32, 2).sum(axis=(1, 3))
    assert np.array_equal((q + 2) >> 2, np.asarray(Image.fromarray(c, "L").reduce(2)))
    lines = [
        "// Generated by tools/engine_tables.py from Pillow's libImaging/ConvertYCbCr.c (its",
        "// RGB to YCbCr, checked on every colour) and devices/yuv.py's tables of the limited",
        "// range.",
        "// Do not edit.",
        "",
    ]
    for name in NAMES:
        lines.append(f"pub const {name.upper()}: [i32; 256] = [{', '.join(map(str, t[name]))}];")
    lines.append("pub const CR_R: [i32; 256] = CB_B;")
    lines.append(f"pub const LIMITED_Y: [u8; 256] = [{', '.join(map(str, LIMITED_Y))}];")
    lines.append(f"pub const LIMITED_C: [u8; 256] = [{', '.join(map(str, LIMITED_C))}];")
    (ROOT / "engine" / "src" / "tables.rs").write_text("\n".join(lines) + "\n")
    print("engine/src/tables.rs written: Pillow's conversion on all 16777216 colours")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
